-- Yoyolov Messages schema for Supabase
-- Run in Supabase Dashboard > SQL Editor. Then enable Anonymous Sign-Ins
-- in Authentication > Providers.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (char_length(trim(username)) between 2 and 24),
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  channel text not null check (channel in ('general','games','help')),
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null check (char_length(trim(username)) between 2 and 24),
  body text not null check (char_length(trim(body)) between 1 and 1000),
  reply_to bigint references public.messages(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.message_reactions (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.messages(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  emoji text not null check (emoji in ('👍','❤️','😂')),
  created_at timestamptz not null default now(),
  unique (message_id,user_id,emoji)
);

create or replace function public.stamp_message_author()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.user_id is distinct from auth.uid() then
    raise exception 'Cannot send as another user';
  end if;
  select p.username into new.username from public.profiles p where p.id = new.user_id;
  if new.username is null then raise exception 'Create a chat profile first'; end if;
  return new;
end;
$$;

drop trigger if exists messages_stamp_author on public.messages;
create trigger messages_stamp_author before insert on public.messages
for each row execute function public.stamp_message_author();

create index if not exists messages_channel_created_idx on public.messages(channel,created_at);
create index if not exists reactions_message_idx on public.message_reactions(message_id);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;
alter table public.message_reactions enable row level security;

drop policy if exists "profiles read by members" on public.profiles;
create policy "profiles read by members" on public.profiles
for select to authenticated using (true);
drop policy if exists "users create own profile" on public.profiles;
create policy "users create own profile" on public.profiles
for insert to authenticated with check (id = auth.uid());
drop policy if exists "users update own profile" on public.profiles;
create policy "users update own profile" on public.profiles
for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "members read messages" on public.messages;
create policy "members read messages" on public.messages
for select to authenticated using (true);
drop policy if exists "members send own messages" on public.messages;
create policy "members send own messages" on public.messages
for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "authors edit own messages" on public.messages;
create policy "authors edit own messages" on public.messages
for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "authors delete own messages" on public.messages;
create policy "authors delete own messages" on public.messages
for delete to authenticated using (user_id = auth.uid());

drop policy if exists "members read reactions" on public.message_reactions;
create policy "members read reactions" on public.message_reactions
for select to authenticated using (true);
drop policy if exists "members react as self" on public.message_reactions;
create policy "members react as self" on public.message_reactions
for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "members remove own reactions" on public.message_reactions;
create policy "members remove own reactions" on public.message_reactions
for delete to authenticated using (user_id = auth.uid());

grant usage on schema public to authenticated;
grant select,insert,update,delete on public.profiles to authenticated;
grant select,insert,update,delete on public.messages to authenticated;
grant select,insert,delete on public.message_reactions to authenticated;
grant usage,select on all sequences in schema public to authenticated;

do $$
begin
  if exists (select 1 from pg_publication where pubname='supabase_realtime') then
    if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='messages') then
      execute 'alter publication supabase_realtime add table public.messages';
    end if;
    if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='message_reactions') then
      execute 'alter publication supabase_realtime add table public.message_reactions';
    end if;
  end if;
end $$;
