-- Yoyolov Chat schema and account-profile setup.
-- Safe to re-run. Existing messages and valid profiles are preserved.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (char_length(trim(username)) between 3 and 20),
  created_at timestamptz not null default now()
);
alter table public.profiles
  add column if not exists created_at timestamptz not null default now();

create unique index if not exists profiles_username_ci_unique
  on public.profiles (lower(username));

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  channel text not null check (channel in ('general','games','help')),
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null check (char_length(trim(username)) between 3 and 20),
  body text not null check (char_length(trim(body)) between 1 and 1000),
  reply_to bigint references public.messages(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.message_reactions (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.messages(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  emoji text not null check (emoji in ('👍','❤️','😂')),
  created_at timestamptz not null default now(),
  unique (message_id,user_id,emoji)
);

-- Remove guest profiles from the previous anonymous-login version; keep messages.
delete from public.profiles p
using auth.users u
where p.id=u.id and coalesce(u.is_anonymous,false)=true;

-- Create a profile transactionally whenever a username/password account is created.
create or replace function public.create_chat_profile()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare requested_name text;
begin
  perform pg_advisory_xact_lock(507202611);
  if (select count(*) from public.profiles) >= 50 then
    raise exception 'Yoyolov Chat is full (50 accounts maximum)';
  end if;

  requested_name := trim(new.raw_user_meta_data->>'username');
  if requested_name is null or requested_name !~ '^[A-Za-z0-9_]{3,20}$' then
    raise exception 'Username must be 3-20 letters, numbers, or underscores';
  end if;
  insert into public.profiles(id,username) values (new.id,requested_name);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_chat_profile on auth.users;
create trigger on_auth_user_created_chat_profile
after insert on auth.users
for each row when (new.raw_user_meta_data ? 'username')
execute function public.create_chat_profile();

-- Backfill accounts created before the trigger was installed.
-- Existing profiles and usernames already claimed by another account are skipped.
insert into public.profiles(id,username)
select u.id, trim(u.raw_user_meta_data->>'username')
from auth.users u
where coalesce(u.is_anonymous,false)=false
  and trim(coalesce(u.raw_user_meta_data->>'username','')) ~ '^[A-Za-z0-9_]{3,20}$'
  and not exists (
    select 1 from public.profiles p
    where lower(p.username)=lower(trim(u.raw_user_meta_data->>'username'))
  )
on conflict (id) do nothing;

-- Never trust the username supplied by a browser when a message is sent.
create or replace function public.stamp_message_author()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if new.user_id is distinct from auth.uid() then
    raise exception 'Cannot send as another user';
  end if;
  select p.username into new.username
  from public.profiles p where p.id=auth.uid();
  if new.username is null then
    raise exception 'Create a chat account first';
  end if;
  return new;
end;
$$;

drop trigger if exists messages_stamp_author on public.messages;
create trigger messages_stamp_author
before insert on public.messages
for each row execute function public.stamp_message_author();

create index if not exists messages_channel_created_idx
  on public.messages(channel,created_at);
create index if not exists reactions_message_idx
  on public.message_reactions(message_id);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;
alter table public.message_reactions enable row level security;

drop policy if exists "profiles read by members" on public.profiles;
create policy "profiles read by members" on public.profiles
for select to authenticated using (true);
drop policy if exists "users create own profile" on public.profiles;
drop policy if exists "users update own profile" on public.profiles;

drop policy if exists "members read messages" on public.messages;
create policy "members read messages" on public.messages
for select to authenticated using (true);
drop policy if exists "members send own messages" on public.messages;
create policy "members send own messages" on public.messages
for insert to authenticated with check (user_id=auth.uid());
drop policy if exists "authors edit own messages" on public.messages;
drop policy if exists "authors delete own messages" on public.messages;
create policy "authors delete own messages" on public.messages
for delete to authenticated using (user_id=auth.uid());

drop policy if exists "members read reactions" on public.message_reactions;
create policy "members read reactions" on public.message_reactions
for select to authenticated using (true);
drop policy if exists "members react as self" on public.message_reactions;
create policy "members react as self" on public.message_reactions
for insert to authenticated with check (user_id=auth.uid());
drop policy if exists "members remove own reactions" on public.message_reactions;
create policy "members remove own reactions" on public.message_reactions
for delete to authenticated using (user_id=auth.uid());

revoke all on public.profiles from anon;
revoke all on public.messages from anon;
revoke all on public.message_reactions from anon;
grant usage on schema public to authenticated;
revoke all on public.profiles from authenticated;
grant select on public.profiles to authenticated;
revoke all on public.messages from authenticated;
grant select,insert,delete on public.messages to authenticated;
revoke all on public.message_reactions from authenticated;
grant select,insert,delete on public.message_reactions to authenticated;
grant usage,select on all sequences in schema public to authenticated;

