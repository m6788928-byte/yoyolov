  null;
end $$;

-- Private one-to-one direct messages.
create table if not exists public.dm_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  sender_username text not null check (char_length(trim(sender_username)) between 3 and 20),
  body text not null check (char_length(trim(body)) between 1 and 1000),
  created_at timestamptz not null default now(),
  constraint dm_no_self_message check (sender_id <> recipient_id)
);

create or replace function public.stamp_dm_sender()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if new.sender_id is distinct from auth.uid() then
    raise exception 'Cannot send a DM as another user';
  end if;
  if not exists (select 1 from public.profiles where id=new.recipient_id) then
    raise exception 'DM recipient does not exist';
  end if;
  select username into new.sender_username
  from public.profiles where id=auth.uid();
  if new.sender_username is null then
    raise exception 'Create a chat account first';
  end if;
  return new;
end;
$$;

drop trigger if exists dm_messages_stamp_sender on public.dm_messages;
create trigger dm_messages_stamp_sender
before insert on public.dm_messages
for each row execute function public.stamp_dm_sender();

create index if not exists dm_messages_sender_created_idx
  on public.dm_messages(sender_id,created_at desc);
create index if not exists dm_messages_recipient_created_idx
  on public.dm_messages(recipient_id,created_at desc);

alter table public.dm_messages enable row level security;
drop policy if exists "participants read DMs" on public.dm_messages;
create policy "participants read DMs" on public.dm_messages
for select to authenticated
using (sender_id=auth.uid() or recipient_id=auth.uid());
drop policy if exists "users send DMs as self" on public.dm_messages;
create policy "users send DMs as self" on public.dm_messages
for insert to authenticated
with check (sender_id=auth.uid() and recipient_id<>auth.uid());
drop policy if exists "senders delete own DMs" on public.dm_messages;
create policy "senders delete own DMs" on public.dm_messages
for delete to authenticated using (sender_id=auth.uid());

revoke all on public.dm_messages from anon;
revoke all on public.dm_messages from authenticated;
grant select,insert,delete on public.dm_messages to authenticated;
grant usage,select on sequence public.dm_messages_id_seq to authenticated;

do $$
begin
  execute 'alter publication supabase_realtime add table public.dm_messages';
exception when duplicate_object then
  null;
end $$;
