-- Friend requests and accepted friendships.
create table if not exists public.friend_requests (
 id bigint generated by default as identity primary key,
 sender_id uuid not null references auth.users(id) on delete cascade,
 recipient_id uuid not null references auth.users(id) on delete cascade,
 status text not null default 'pending' check(status in ('pending','accepted')),
 created_at timestamptz not null default now(),
 constraint friend_request_not_self check(sender_id<>recipient_id),
 unique(sender_id,recipient_id)
);
alter table public.friend_requests enable row level security;
drop policy if exists "friend requests visible to participants" on public.friend_requests;
create policy "friend requests visible to participants" on public.friend_requests for select to authenticated using(sender_id=auth.uid() or recipient_id=auth.uid());
drop policy if exists "send friend requests as self" on public.friend_requests;
create policy "send friend requests as self" on public.friend_requests for insert to authenticated with check(sender_id=auth.uid());
drop policy if exists "recipients accept friend requests" on public.friend_requests;
create policy "recipients accept friend requests" on public.friend_requests for update to authenticated using(recipient_id=auth.uid() and status='pending') with check(recipient_id=auth.uid() and status='accepted');
drop policy if exists "participants remove friend requests" on public.friend_requests;
create policy "participants remove friend requests" on public.friend_requests for delete to authenticated using(sender_id=auth.uid() or recipient_id=auth.uid());
grant select,insert,update,delete on public.friend_requests to authenticated;
grant usage,select on sequence public.friend_requests_id_seq to authenticated;

-- Group chats and membership.
create table if not exists public.group_chats (
 id uuid primary key default gen_random_uuid(),
 name text not null check(char_length(trim(name)) between 1 and 40),
 owner_id uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
create table if not exists public.group_members (
 group_id uuid not null references public.group_chats(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 joined_at timestamptz not null default now(),
 primary key(group_id,user_id)
);
create or replace function public.is_group_member(gid uuid)
returns boolean language sql stable security definer set search_path=public
as 'select exists(select 1 from public.group_members where group_id=gid and user_id=auth.uid())';
create or replace function public.is_group_owner(gid uuid)
returns boolean language sql stable security definer set search_path=public
as 'select exists(select 1 from public.group_chats where id=gid and owner_id=auth.uid())';
alter table public.group_chats enable row level security;
alter table public.group_members enable row level security;
drop policy if exists "members view their groups" on public.group_chats;
create policy "members view their groups" on public.group_chats for select to authenticated using(public.is_group_member(id) or owner_id=auth.uid());
drop policy if exists "users create groups" on public.group_chats;
create policy "users create groups" on public.group_chats for insert to authenticated with check(owner_id=auth.uid());
drop policy if exists "owners update groups" on public.group_chats;
create policy "owners update groups" on public.group_chats for update to authenticated using(owner_id=auth.uid()) with check(owner_id=auth.uid());
drop policy if exists "owners delete groups" on public.group_chats;
create policy "owners delete groups" on public.group_chats for delete to authenticated using(owner_id=auth.uid());
drop policy if exists "members see group membership" on public.group_members;
create policy "members see group membership" on public.group_members for select to authenticated using(public.is_group_member(group_id) or public.is_group_owner(group_id));
drop policy if exists "owners add group members" on public.group_members;
create policy "owners add group members" on public.group_members for insert to authenticated with check(public.is_group_owner(group_id) or user_id=auth.uid() and exists(select 1 from public.group_chats g where g.id=group_id and g.owner_id=auth.uid()));
drop policy if exists "owners remove group members" on public.group_members;
create policy "owners remove group members" on public.group_members for delete to authenticated using(public.is_group_owner(group_id) or user_id=auth.uid());
create table if not exists public.group_messages (
 id bigint generated by default as identity primary key,
 group_id uuid not null references public.group_chats(id) on delete cascade,
 sender_id uuid not null references auth.users(id) on delete cascade,
 body text not null check(char_length(trim(body)) between 1 and 1000),
 attachment_path text, attachment_name text, attachment_size bigint,
 created_at timestamptz not null default now()
);
alter table public.group_messages enable row level security;
